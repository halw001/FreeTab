const translations: Record<Locale, Translations> = { en, zh_CN, zh_TW, es, ja, ko, de, vi, pt_BR, fr, ru, it, tr, pl, nl };

export function getTranslations(locale: Locale): Translations {
  return translations[locale] ?? translations.en;
}

export function t(locale: Locale, key: keyof Translations, params?: Record<string, string | number>): string {
  const dict = translations[locale] ?? translations.en;
  let value: string = dict[key] ?? translations.en[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      value = value.replace(`{${k}}`, String(v));
    });
  }
  return value;
}